"""Agent 5 - the reply handler, built with the OpenAI Agents SDK (lesson 4.6).

Input : fictional replies to our step 4 emails (data/replies_sample.jsonl)
Output: one ReplyDecision per reply, a CRM file, a do-not-contact list and
        reply drafts in data/output/replies/ (NEVER sent)

Three agents work together:

    reply ──► [input guardrail: opt-out?] ──► triage ─┬─► decides itself (not now, out of office, ...)
              (plain code, no model)                  ├─► hands off to scheduler (wants a call)
                                                      └─► hands off to answerer  (asks a question)
                                                 ▼
                                [output guardrail: rules checked by code]
                                                 ▼
                       code updates crm.csv / do_not_contact.csv / drafts

What the SDK gives us that we wrote by hand before:
  - the function-calling loop of step 1b (Runner runs it: tool call, result, repeat)
  - handoffs: one agent passes the conversation to a specialist
  - guardrails: checks that run before the first agent and after the last one
  - max_turns: the same safety limit as MAX_SEARCH_ROUNDS in step 1b

Principles kept from earlier steps:
  - tools only READ (lead data, the email we sent, the knowledge base, free slots);
    CODE writes files from the final decision: an agent can't corrupt the CRM
  - what must always be right is done by code: an opt-out never reaches a model
  - the reply text is DATA from outside: instructions inside it are not obeyed

Course lessons used here:
  4.6 Agents SDK         - Agent, Runner, function_tool, handoffs, guardrails
  4.2 Function calling   - the tools (now declared with @function_tool)
  2.5 Structured Outputs - output_type=ReplyDecision on every agent
"""
